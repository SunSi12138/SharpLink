namespace SharpLink.Generator;

public partial class RpcGenerator
{
    private static string GenerateProxy(
        string manifestTypeName,
        RpcInterfaceModel model,
        IReadOnlyDictionary<string, string> concreteCodecTypes)
    {
        var body = new StringBuilder();
        AppendProxyClassBody(body, model, concreteCodecTypes);

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using SharpLink.Abstractions;");
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Buffers;");
        sb.AppendLine("using System.Buffers.Binary;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using System.IO;");
        sb.AppendLine("using System.Runtime.CompilerServices;");
        sb.AppendLine("using System.Threading;");
        sb.AppendLine("using System.Threading.Tasks;");
        sb.AppendLine();
        sb.AppendLine("namespace SharpLink.Generated;");
        sb.AppendLine();
        sb.AppendLine($"public sealed partial class {manifestTypeName}");
        sb.AppendLine("{");
        sb.AppendLine($"    private sealed class __Proxy_{GetContractArtifactIdentity(model)} : {model.FullName}");
        sb.AppendLine("    {");
        sb.Append(Indent(body.ToString(), "    "));
        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static string GenerateProxyHelpers(
        RpcInterfaceModel model,
        IReadOnlyDictionary<string, string> concreteCodecTypes)
    {
        var nsDeclaration = string.IsNullOrEmpty(model.Namespace) ? "" : $"namespace {model.Namespace};";
        var sb = new StringBuilder();
        sb.AppendLine($$"""
                        // <auto-generated/>
                        #nullable enable
                        using SharpLink.Abstractions;
                        using System;
                        using System.Buffers;
                        using System.Buffers.Binary;
                        using System.Collections.Generic;
                        using System.IO;
                        using System.Runtime.CompilerServices;
                        using System.Threading;
                        using System.Threading.Tasks;

                        {{nsDeclaration}}
                        """);

        var emittedAny = false;
        foreach (var method in model.Methods)
        {
            if (GetPayloadParameters(method).Length != 0)
            {
                AppendGeneratedRequest(sb, model, method, concreteCodecTypes);
                emittedAny = true;
            }
            if (GetStreamParameters(method).Length != 0)
            {
                AppendGeneratedStreams(sb, model, method, concreteCodecTypes);
                emittedAny = true;
            }
        }

        return emittedAny ? sb.ToString() : string.Empty;
    }

    private static void AppendProxyClassBody(
        StringBuilder sb,
        RpcInterfaceModel model,
        IReadOnlyDictionary<string, string> concreteCodecTypes)
    {
        sb.AppendLine("    private readonly IRpcChannel _channel;");

        foreach (var method in model.Methods)
            AppendProxyFields(sb, model, method, concreteCodecTypes);

        sb.AppendLine($"    internal __Proxy_{GetContractArtifactIdentity(model)}(IRpcChannel channel, IRpcCodecProvider __codecs)");
        sb.AppendLine("    {");
        sb.AppendLine("        ArgumentNullException.ThrowIfNull(channel);");
        sb.AppendLine("        ArgumentNullException.ThrowIfNull(__codecs);");
        sb.AppendLine("        _channel = channel;");
        foreach (var method in model.Methods)
        {
            var suffix = GetMethodSuffix(method);
            var payloadParameters = GetPayloadParameters(method);
            if (payloadParameters.Length != 0)
                sb.AppendLine($"        __requestCodec_{suffix} = new {GetHelperTypeReference(model, GetRequestCodecType(model, method))}(__codecs).StaticCore;");
            if (!method.IsOneWay)
                sb.AppendLine($"        __responseCodec_{suffix} = {GetCodecHotResolveExpression("__codecs", GetResponseType(method), GetResponseCodecLookupType(method), concreteCodecTypes)};");
            var streamParameters = GetStreamParameters(method);
            for (var index = 0; index < streamParameters.Length; index++)
            {
                sb.AppendLine($"        __streamCodec_{suffix}_{index} = {GetCodecHotResolveExpression("__codecs", streamParameters[index].DisplayStreamItemType!, streamParameters[index].StreamItemType!, concreteCodecTypes)};");
            }
        }
        sb.AppendLine("    }");

        foreach (var method in model.Methods)
            AppendProxyMethod(sb, model, method, concreteCodecTypes);
    }

    private static void AppendProxyFields(
        StringBuilder sb,
        RpcInterfaceModel model,
        RpcMethodModel method,
        IReadOnlyDictionary<string, string> concreteCodecTypes)
    {
        var suffix = GetMethodSuffix(method);
        var kind = GetMethodKind(method);
        var hasPayloadResponse = !method.IsOneWay && !method.IsVoid;
        var clientStreamCount = GetStreamParameters(method).Length;
        var hasClientStreams = clientStreamCount != 0;
        var methodTimeout = method.TimeoutTicks is { } ticks
            ? $"TimeSpan.FromTicks({ticks.ToString(InvariantCulture)}L)"
            : "null";
        sb.AppendLine(
            $"    private static readonly RpcMethodDescriptor __method_{suffix} = new({model.Hash}L, {method.Hash}L, RpcMethodKind.{kind}, {(hasPayloadResponse ? "true" : "false")}, {(hasClientStreams ? "true" : "false")}, {(method.HasTimeoutAttribute ? "true" : "false")}, {methodTimeout}, {(method.IsIdempotent ? "true" : "false")}, {clientStreamCount}, {(method.ResponseNullable ? "true" : "false")});");

        if (GetPayloadParameters(method).Length != 0)
            sb.AppendLine($"    private readonly {GetHelperTypeReference(model, GetRequestCodecType(model, method))}.Core __requestCodec_{suffix};");
        if (!method.IsOneWay)
            sb.AppendLine($"    private readonly {GetCodecHotStorageType(GetResponseType(method), GetResponseCodecLookupType(method), concreteCodecTypes)} __responseCodec_{suffix};");
        var streamParameters = GetStreamParameters(method);
        for (var index = 0; index < streamParameters.Length; index++)
            sb.AppendLine($"    private readonly {GetCodecHotStorageType(streamParameters[index].DisplayStreamItemType!, streamParameters[index].StreamItemType!, concreteCodecTypes)} __streamCodec_{suffix}_{index};");
    }

    private static void AppendProxyMethod(
        StringBuilder sb,
        RpcInterfaceModel model,
        RpcMethodModel method,
        IReadOnlyDictionary<string, string> concreteCodecTypes)
    {
        var suffix = GetMethodSuffix(method);
        var parameterList = string.Join(", ", method.Parameters.Select(parameter => $"{parameter.DisplayType} {EscapeIdentifier(parameter.Name)}"));
        var payloadParameters = GetPayloadParameters(method);
        var streamParameters = GetStreamParameters(method);
        var requestType = payloadParameters.Length == 0 ? "RpcEmptyRequest" : GetHelperTypeReference(model, GetRequestType(model, method));
        var requestCodec = payloadParameters.Length == 0 ? "RpcEmptyRequestCodec.Instance" : $"__requestCodec_{suffix}";
        var requestCodecType = payloadParameters.Length == 0
            ? "RpcEmptyRequestCodec"
            : GetHelperTypeReference(model, GetRequestCodecType(model, method)) + ".Core";
        var responseType = GetResponseType(method);
        var responseCodecType = method.IsOneWay
            ? string.Empty
            : GetCodecHotStorageType(responseType, GetResponseCodecLookupType(method), concreteCodecTypes);
        var requestValue = payloadParameters.Length == 0
            ? "default(RpcEmptyRequest)"
            : $"new {requestType}({string.Join(", ", payloadParameters.Select(static parameter => EscapeIdentifier(parameter.Name)))})";
        var streamsType = streamParameters.Length == 0 ? "RpcNoClientStreams" : GetHelperTypeReference(model, GetStreamsType(model, method));
        var streamsValue = streamParameters.Length == 0
            ? "default(RpcNoClientStreams)"
            : $"new {streamsType}({string.Join(", ", streamParameters.Select((parameter, index) => $"{EscapeIdentifier(parameter.Name)}, __streamCodec_{suffix}_{index}"))})";
        var cancellationParameter = method.Parameters.FirstOrDefault(static parameter => parameter.IsCancellationToken);
        var cancellationToken = cancellationParameter is null ? "default" : EscapeIdentifier(cancellationParameter.Name);
        var requestLocal = GetUniqueGeneratedLocalName(method, "__request");
        var streamsLocal = GetUniqueGeneratedLocalName(method, "__streams");

        sb.AppendLine($"    public {method.DisplayReturnType} {EscapeIdentifier(method.Name)}({parameterList})");
        sb.AppendLine("    {");
        sb.AppendLine($"        var {requestLocal} = {requestValue};");
        if (streamParameters.Length != 0 || method.IsOneWay)
            sb.AppendLine($"        var {streamsLocal} = {streamsValue};");

        string invocation;
        if (method.IsStreamReturn)
        {
            invocation = streamParameters.Length == 0
                ? $"_channel.InvokeGeneratedServerStreamingAsync<{requestType}, {responseType}, {requestCodecType}, {responseCodecType}>(__method_{suffix}, in {requestLocal}, {requestCodec}, __responseCodec_{suffix}, default, {cancellationToken})"
                : $"_channel.InvokeGeneratedDuplexStreamingAsync<{requestType}, {responseType}, {requestCodecType}, {responseCodecType}, {streamsType}>(__method_{suffix}, in {requestLocal}, {requestCodec}, __responseCodec_{suffix}, in {streamsLocal}, default, {cancellationToken})";
            sb.AppendLine($"        return {invocation};");
        }
        else if (method.IsOneWay)
        {
            invocation = $"_channel.InvokeGeneratedOneWayAsync<{requestType}, {requestCodecType}, {streamsType}>(__method_{suffix}, in {requestLocal}, {requestCodec}, in {streamsLocal}, default, {cancellationToken})";
            AppendTaskLikeReturn(sb, method, invocation, hasResult: false);
        }
        else if (streamParameters.Length != 0)
        {
            invocation = $"_channel.InvokeGeneratedClientStreamingAsync<{requestType}, {responseType}, {requestCodecType}, {responseCodecType}, {streamsType}>(__method_{suffix}, in {requestLocal}, {requestCodec}, __responseCodec_{suffix}, in {streamsLocal}, default, {cancellationToken})";
            AppendTaskLikeReturn(sb, method, invocation, hasResult: !method.IsVoid);
        }
        else
        {
            invocation = $"_channel.InvokeGeneratedUnaryAsync<{requestType}, {responseType}, {requestCodecType}, {responseCodecType}>(__method_{suffix}, in {requestLocal}, {requestCodec}, __responseCodec_{suffix}, default, {cancellationToken})";
            AppendTaskLikeReturn(sb, method, invocation, hasResult: !method.IsVoid);
        }

        sb.AppendLine("    }");
    }

    private static string GetUniqueGeneratedLocalName(RpcMethodModel method, string preferred)
    {
        var candidate = preferred;
        while (true)
        {
            var collision = false;
            foreach (var parameter in method.Parameters)
            {
                if (!string.Equals(parameter.Name, candidate, StringComparison.Ordinal))
                    continue;
                collision = true;
                break;
            }
            if (!collision)
                return candidate;
            candidate += "_";
        }
    }

    private static void AppendTaskLikeReturn(
        StringBuilder sb,
        RpcMethodModel method,
        string invocation,
        bool hasResult)
    {
        var returnsValueTask = method.ReturnsValueTask;
        if (hasResult)
        {
            sb.AppendLine(returnsValueTask
                ? $"        return {invocation};"
                : $"        return {invocation}.AsTask();");
            return;
        }

        if (!method.IsOneWay)
            invocation += ".AsVoid()";
        sb.AppendLine(returnsValueTask
            ? $"        return {invocation};"
            : $"        return {invocation}.AsTask();");
    }

    private static void AppendGeneratedRequest(
        StringBuilder sb,
        RpcInterfaceModel model,
        RpcMethodModel method,
        IReadOnlyDictionary<string, string> concreteCodecTypes)
    {
        var requestType = GetRequestType(model, method);
        var codecType = GetRequestCodecType(model, method);
        var parameters = GetPayloadParameters(method);
        var blittable = parameters.Where(static parameter => parameter.IsBlittable).ToArray();
        var complex = parameters.Where(static parameter => !parameter.IsBlittable).ToArray();

        sb.AppendLine($"internal readonly struct {requestType}");
        sb.AppendLine("{");
        foreach (var parameter in parameters)
            sb.AppendLine($"    internal readonly {parameter.DisplayType} {EscapeIdentifier(parameter.Name)};");
        sb.AppendLine($"    internal {requestType}({string.Join(", ", parameters.Select(static parameter => $"{parameter.DisplayType} {EscapeIdentifier(parameter.Name)}"))})");
        sb.AppendLine("    {");
        foreach (var parameter in parameters)
            sb.AppendLine($"        this.{EscapeIdentifier(parameter.Name)} = {EscapeIdentifier(parameter.Name)};");
        sb.AppendLine("    }");
        sb.AppendLine("}");

        sb.AppendLine($"internal sealed class {codecType} : IRpcCodec<{requestType}>, IRpcSizedCodec<{requestType}>");
        sb.AppendLine("{");
        foreach (var parameter in complex)
        {
            sb.AppendLine($"    private readonly {GetCodecStorageType(parameter.DisplayType, parameter.Type, concreteCodecTypes)} __codec_{parameter.Name};");
            sb.AppendLine($"    private readonly IRpcSizedCodec<{parameter.DisplayType}>? __sizedCodec_{parameter.Name};");
        }
        if (complex.Length != 0)
        {
            sb.AppendLine("    private readonly bool __canExactSize;");
            sb.AppendLine("    private readonly global::System.Collections.Concurrent.ConcurrentBag<__SizedSnapshot> __sizedSnapshots = new();");
        }
        sb.AppendLine($"    internal {codecType}(IRpcCodecProvider codecs)");
        sb.AppendLine("    {");
        sb.AppendLine("        ArgumentNullException.ThrowIfNull(codecs);");
        foreach (var parameter in complex)
        {
            sb.AppendLine($"        __codec_{parameter.Name} = {GetCodecResolveExpression("codecs", parameter.DisplayType, parameter.Type, concreteCodecTypes)};");
            sb.AppendLine($"        __sizedCodec_{parameter.Name} = __codec_{parameter.Name} as IRpcSizedCodec<{parameter.DisplayType}>;");
        }
        if (complex.Length != 0)
        {
            sb.AppendLine(
                $"        __canExactSize = {string.Join(" && ", complex.Select(static parameter => $"__sizedCodec_{parameter.Name} is {{ CanExactSize: true }}"))};");
        }
        sb.AppendLine("    }");
        sb.AppendLine();

        if (complex.Length != 0)
        {
            AppendGeneratedRequestSnapshotType(sb, parameters, complex);
            sb.AppendLine();
        }

        AppendGeneratedRequestCodecMethods(sb, requestType, parameters, blittable, complex);
        sb.AppendLine();
        AppendGeneratedRequestSizingMethods(
            sb,
            requestType,
            parameters,
            blittable,
            complex,
            useHotChildCores: false,
            concreteCodecTypes);

        sb.AppendLine();
        sb.AppendLine("    internal Core StaticCore => new(this);");
        sb.AppendLine();
        sb.AppendLine($"    internal readonly struct Core : IRpcCodec<{requestType}>, IRpcSizedCodec<{requestType}>");
        sb.AppendLine("    {");
        if (complex.Length != 0)
            sb.AppendLine($"        private readonly {codecType} __owner;");
        foreach (var parameter in complex)
        {
            sb.AppendLine($"        private readonly {GetCodecHotStorageType(parameter.DisplayType, parameter.Type, concreteCodecTypes)} __codec_{parameter.Name};");
            if (!TryGetStaticGeneratedCodecCoreType(parameter.Type, concreteCodecTypes, out _))
                sb.AppendLine($"        private readonly IRpcSizedCodec<{parameter.DisplayType}>? __sizedCodec_{parameter.Name};");
        }
        if (complex.Length != 0)
            sb.AppendLine("        private readonly bool __canExactSize;");
        if (complex.Length != 0)
            sb.AppendLine();
        sb.AppendLine($"        internal Core({codecType} owner)");
        sb.AppendLine("        {");
        if (complex.Length != 0)
            sb.AppendLine("            __owner = owner;");
        foreach (var parameter in complex)
        {
            if (TryGetStaticGeneratedCodecCoreType(parameter.Type, concreteCodecTypes, out _))
            {
                sb.AppendLine($"            __codec_{parameter.Name} = owner.__codec_{parameter.Name}.StaticCore;");
            }
            else
            {
                sb.AppendLine($"            __codec_{parameter.Name} = owner.__codec_{parameter.Name};");
                sb.AppendLine($"            __sizedCodec_{parameter.Name} = owner.__sizedCodec_{parameter.Name};");
            }
        }
        if (complex.Length != 0)
        {
            var checks = complex.Select(parameter =>
                TryGetStaticGeneratedCodecCoreType(parameter.Type, concreteCodecTypes, out _)
                    ? $"__codec_{parameter.Name}.CanExactSize"
                    : $"__sizedCodec_{parameter.Name} is {{ CanExactSize: true }}");
            sb.AppendLine($"            __canExactSize = {string.Join(" && ", checks)};");
        }
        sb.AppendLine("        }");
        if (complex.Length != 0)
        {
            sb.AppendLine();
            sb.AppendLine("        private __SizedSnapshot RentSnapshot() => __owner.RentSnapshot();");
            sb.AppendLine("        private void ReturnSnapshot(__SizedSnapshot snapshot) => __owner.ReturnSnapshot(snapshot);");
        }
        sb.AppendLine();

        var coreMethods = new StringBuilder();
        AppendGeneratedRequestCodecMethods(coreMethods, requestType, parameters, blittable, complex);
        coreMethods.AppendLine();
        AppendGeneratedRequestSizingMethods(
            coreMethods,
            requestType,
            parameters,
            blittable,
            complex,
            useHotChildCores: true,
            concreteCodecTypes);
        sb.Append(Indent(coreMethods.ToString(), "    "));
        sb.AppendLine("    }");
        sb.AppendLine("}");
    }

    private static void AppendGeneratedRequestSnapshotType(
        StringBuilder sb,
        RpcParameterModel[] parameters,
        RpcParameterModel[] complex)
    {
        sb.AppendLine("    private sealed class __SizedSnapshot : IRpcSizedCodecSnapshot");
        sb.AppendLine("    {");
        foreach (var parameter in parameters)
            sb.AppendLine($"        internal {parameter.DisplayType} __value_{parameter.Name} = default!;");
        foreach (var parameter in complex)
        {
            sb.AppendLine($"        internal int __nestedSize_{parameter.Name};");
            sb.AppendLine($"        internal IRpcSizedCodecSnapshot? __nestedSnapshot_{parameter.Name};");
        }
        sb.AppendLine();
        sb.AppendLine("        internal void Reset()");
        sb.AppendLine("        {");
        foreach (var parameter in parameters)
            sb.AppendLine($"            __value_{parameter.Name} = default!;");
        foreach (var parameter in complex)
        {
            sb.AppendLine($"            __nestedSize_{parameter.Name} = 0;");
            sb.AppendLine($"            __nestedSnapshot_{parameter.Name} = null;");
        }
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    private __SizedSnapshot RentSnapshot()");
        sb.AppendLine("        => __sizedSnapshots.TryTake(out var snapshot) ? snapshot : new __SizedSnapshot();");
        sb.AppendLine();
        sb.AppendLine("    private void ReturnSnapshot(__SizedSnapshot snapshot)");
        sb.AppendLine("    {");
        sb.AppendLine("        snapshot.Reset();");
        sb.AppendLine("        __sizedSnapshots.Add(snapshot);");
        sb.AppendLine("    }");
    }

    private static void AppendGeneratedRequestCodecMethods(
        StringBuilder sb,
        string requestType,
        RpcParameterModel[] parameters,
        RpcParameterModel[] blittable,
        RpcParameterModel[] complex)
    {
        sb.AppendLine($"    public void Serialize(in {requestType} value, IBufferWriter<byte> writer)");
        sb.AppendLine("    {");
        sb.AppendLine("        ArgumentNullException.ThrowIfNull(writer);");
        sb.AppendLine("        if (CanExactSize &&");
        sb.AppendLine("            writer is IRpcByteBufferWriter __exactWriter &&");
        sb.AppendLine("            !RpcGeneratedCodecSizing.IsSuppressed &&");
        sb.AppendLine("            TryGetEncodedSize(in value, out var __exactSize, out var __sizedSnapshot))");
        sb.AppendLine("        {");
        sb.AppendLine("            try");
        sb.AppendLine("            {");
        sb.AppendLine("                __exactWriter.GetSpan(checked(__exactSize + 4));");
        sb.AppendLine("                __exactWriter.Advance(0);");
        sb.AppendLine("                RpcGeneratedCodecSizing.Enter();");
        sb.AppendLine("                try");
        sb.AppendLine("                {");
        sb.AppendLine("                    SerializeSized(in value, writer, __exactSize, __sizedSnapshot);");
        sb.AppendLine("                }");
        sb.AppendLine("                finally");
        sb.AppendLine("                {");
        sb.AppendLine("                    RpcGeneratedCodecSizing.Exit();");
        sb.AppendLine("                }");
        sb.AppendLine("            }");
        sb.AppendLine("            finally");
        sb.AppendLine("            {");
        sb.AppendLine("                ReleaseSnapshot(__sizedSnapshot);");
        sb.AppendLine("            }");
        sb.AppendLine("            return;");
        sb.AppendLine("        }");

        if (blittable.Length != 0)
        {
            var total = string.Join(" + ", blittable.Select(parameter => GetInlineSizeToken(parameter.Type)));
            sb.AppendLine($"        var fixedSize = {total};");
            sb.AppendLine("        var fixedSpan = writer.GetSpan(fixedSize);");
            sb.AppendLine("        var fixedOffset = 0;");
            foreach (var parameter in blittable)
            {
                var size = GetInlineSizeToken(parameter.Type);
                if (IsBooleanType(parameter.Type))
                    sb.AppendLine($"        fixedSpan[fixedOffset] = value.{EscapeIdentifier(parameter.Name)} ? (byte)1 : (byte)0;");
                else
                    sb.AppendLine($"        Unsafe.WriteUnaligned(ref System.Runtime.InteropServices.MemoryMarshal.GetReference(fixedSpan.Slice(fixedOffset, {size})), value.{EscapeIdentifier(parameter.Name)});");
                sb.AppendLine($"        fixedOffset += {size};");
            }
            sb.AppendLine("        writer.Advance(fixedSize);");
        }
        if (complex.Length != 0)
            sb.AppendLine("        var rpcWriter = writer as IRpcByteBufferWriter ?? throw new InvalidOperationException(\"Generated request codecs require the SharpLink packet writer.\");");
        for (var index = 0; index < complex.Length; index++)
        {
            var parameter = complex[index];
            sb.AppendLine($"        var lengthOffset_{index} = rpcWriter.WrittenCount;");
            sb.AppendLine("        writer.GetSpan(sizeof(int));");
            sb.AppendLine("        writer.Advance(sizeof(int));");
            sb.AppendLine($"        var start_{index} = rpcWriter.WrittenCount;");
            sb.AppendLine($"        __codec_{parameter.Name}.Serialize(value.{EscapeIdentifier(parameter.Name)}!, writer);");
            sb.AppendLine($"        var length_{index} = rpcWriter.WrittenCount - start_{index};");
            sb.AppendLine($"        var written_{index} = rpcWriter.WrittenSpan;");
            sb.AppendLine($"        BinaryPrimitives.WriteInt32LittleEndian(written_{index}.Slice(lengthOffset_{index}, sizeof(int)), length_{index});");
        }
        sb.AppendLine("    }");

        sb.AppendLine($"    public {requestType} Deserialize(in ReadOnlySequence<byte> payload)");
        sb.AppendLine("    {");
        sb.AppendLine("        var reader = new SequenceReader<byte>(payload);");
        foreach (var parameter in blittable)
        {
            var size = GetInlineSizeToken(parameter.Type);
            if (IsBooleanType(parameter.Type))
            {
                sb.AppendLine($"        if (!reader.TryRead(out var marker_{parameter.Name}) || marker_{parameter.Name} is not (0 or 1))");
                sb.AppendLine($"            throw RpcGeneratedCodecWire.DataLoss(\"Request field '{parameter.Name}' has an invalid Boolean marker.\");");
                sb.AppendLine($"        var value_{parameter.Name} = marker_{parameter.Name} == 1;");
                continue;
            }
            sb.AppendLine($"        if (reader.Remaining < {size}) throw RpcGeneratedCodecWire.DataLoss(\"Request field '{parameter.Name}' is truncated.\");");
            sb.AppendLine($"        {parameter.Type} value_{parameter.Name};");
            sb.AppendLine($"        if (reader.UnreadSpan.Length >= {size})");
            sb.AppendLine($"            value_{parameter.Name} = Unsafe.ReadUnaligned<{parameter.Type}>(in System.Runtime.InteropServices.MemoryMarshal.GetReference(reader.UnreadSpan));");
            sb.AppendLine("        else");
            sb.AppendLine("        {");
            sb.AppendLine($"            Span<byte> temporary_{parameter.Name} = stackalloc byte[{size}];");
            sb.AppendLine($"            if (!reader.TryCopyTo(temporary_{parameter.Name})) throw RpcGeneratedCodecWire.DataLoss(\"Request field is truncated.\");");
            sb.AppendLine($"            value_{parameter.Name} = Unsafe.ReadUnaligned<{parameter.Type}>(in System.Runtime.InteropServices.MemoryMarshal.GetReference(temporary_{parameter.Name}));");
            sb.AppendLine("        }");
            sb.AppendLine($"        reader.Advance({size});");
        }
        foreach (var parameter in complex)
        {
            sb.AppendLine($"        if (!reader.TryReadLittleEndian(out int length_{parameter.Name}) || length_{parameter.Name} < 0 || reader.Remaining < length_{parameter.Name})");
            sb.AppendLine($"            throw RpcGeneratedCodecWire.DataLoss(\"Request field '{parameter.Name}' has an invalid length.\");");
            sb.AppendLine($"        var payload_{parameter.Name} = reader.UnreadSequence.Slice(0, length_{parameter.Name});");
            var nullGuard = parameter.IsValueType || parameter.IsNullableReference
                ? ""
                : $" ?? throw RpcGeneratedCodecWire.DataLoss(\"Request field '{parameter.Name}' is null.\")";
            sb.AppendLine($"        var value_{parameter.Name} = __codec_{parameter.Name}.Deserialize(payload_{parameter.Name}){nullGuard};");
            sb.AppendLine($"        reader.Advance(length_{parameter.Name});");
        }
        sb.AppendLine("        if (reader.Remaining != 0) throw RpcGeneratedCodecWire.DataLoss(\"Request contains trailing data.\");");
        sb.AppendLine($"        return new {requestType}({string.Join(", ", parameters.Select(static parameter => $"value_{parameter.Name}"))});");
        sb.AppendLine("    }");
    }

    private static void AppendGeneratedRequestSizingMethods(
        StringBuilder sb,
        string requestType,
        RpcParameterModel[] parameters,
        RpcParameterModel[] blittable,
        RpcParameterModel[] complex,
        bool useHotChildCores,
        IReadOnlyDictionary<string, string> concreteCodecTypes)
    {
        var fixedSize = blittable.Length == 0
            ? "0"
            : string.Join(" + ", blittable.Select(parameter => GetInlineSizeToken(parameter.Type)));

        sb.AppendLine(complex.Length == 0
            ? "    public bool CanExactSize => true;"
            : "    public bool CanExactSize => __canExactSize;");
        sb.AppendLine();
        sb.AppendLine($"    public bool TryGetEncodedSize(in {requestType} value, out int size)");
        sb.AppendLine("    {");
        sb.AppendLine($"        size = {fixedSize};");
        foreach (var parameter in complex)
        {
            var field = $"value.{EscapeIdentifier(parameter.Name)}";
            if (useHotChildCores &&
                TryGetStaticGeneratedCodecCoreType(parameter.Type, concreteCodecTypes, out _))
            {
                sb.AppendLine($"        if (!__codec_{parameter.Name}.CanExactSize ||");
                sb.AppendLine($"            !__codec_{parameter.Name}.TryGetEncodedSize({field}!, out var __nestedSize_{parameter.Name}))");
            }
            else
            {
                sb.AppendLine($"        var __sized_{parameter.Name} = __sizedCodec_{parameter.Name};");
                sb.AppendLine($"        if (__sized_{parameter.Name} is null ||");
                sb.AppendLine($"            !__sized_{parameter.Name}.CanExactSize ||");
                sb.AppendLine($"            !__sized_{parameter.Name}.TryGetEncodedSize({field}!, out var __nestedSize_{parameter.Name}))");
            }
            sb.AppendLine("        {");
            sb.AppendLine("            size = 0;");
            sb.AppendLine("            return false;");
            sb.AppendLine("        }");
            sb.AppendLine($"        size = checked(size + sizeof(int) + __nestedSize_{parameter.Name});");
        }
        sb.AppendLine("        return true;");
        sb.AppendLine("    }");
        sb.AppendLine();

        sb.AppendLine($"    public bool TryGetEncodedSize(in {requestType} value, out int size, out IRpcSizedCodecSnapshot? snapshot)");
        sb.AppendLine("    {");
        if (complex.Length == 0)
        {
            sb.AppendLine($"        size = {fixedSize};");
            sb.AppendLine("        snapshot = null;");
            sb.AppendLine("        return true;");
        }
        else
        {
            sb.AppendLine($"        size = {fixedSize};");
            sb.AppendLine("        snapshot = null;");
            sb.AppendLine("        var __snapshot = RentSnapshot();");
            sb.AppendLine("        var __keepSnapshot = false;");
            sb.AppendLine("        try");
            sb.AppendLine("        {");
            foreach (var parameter in parameters)
                sb.AppendLine($"            __snapshot.__value_{parameter.Name} = value.{EscapeIdentifier(parameter.Name)};");
            foreach (var parameter in complex)
            {
                if (useHotChildCores &&
                    TryGetStaticGeneratedCodecCoreType(parameter.Type, concreteCodecTypes, out _))
                {
                    sb.AppendLine($"            if (!__codec_{parameter.Name}.CanExactSize ||");
                    sb.AppendLine($"                !__codec_{parameter.Name}.TryGetEncodedSize(__snapshot.__value_{parameter.Name}!, out __snapshot.__nestedSize_{parameter.Name}, out __snapshot.__nestedSnapshot_{parameter.Name}))");
                }
                else
                {
                    sb.AppendLine($"            var __sized_{parameter.Name} = __sizedCodec_{parameter.Name};");
                    sb.AppendLine($"            if (__sized_{parameter.Name} is null ||");
                    sb.AppendLine($"                !__sized_{parameter.Name}.CanExactSize ||");
                    sb.AppendLine($"                !__sized_{parameter.Name}.TryGetEncodedSize(__snapshot.__value_{parameter.Name}!, out __snapshot.__nestedSize_{parameter.Name}, out __snapshot.__nestedSnapshot_{parameter.Name}))");
                }
                sb.AppendLine("            {");
                sb.AppendLine("                size = 0;");
                sb.AppendLine("                return false;");
                sb.AppendLine("            }");
                sb.AppendLine($"            size = checked(size + sizeof(int) + __snapshot.__nestedSize_{parameter.Name});");
            }
            sb.AppendLine("            snapshot = __snapshot;");
            sb.AppendLine("            __keepSnapshot = true;");
            sb.AppendLine("            return true;");
            sb.AppendLine("        }");
            sb.AppendLine("        finally");
            sb.AppendLine("        {");
            sb.AppendLine("            if (!__keepSnapshot)");
            sb.AppendLine("            {");
            sb.AppendLine("                try");
            sb.AppendLine("                {");
            sb.AppendLine("                    ReleaseCapturedChildren(__snapshot);");
            sb.AppendLine("                }");
            sb.AppendLine("                finally");
            sb.AppendLine("                {");
            sb.AppendLine("                    ReturnSnapshot(__snapshot);");
            sb.AppendLine("                }");
            sb.AppendLine("            }");
            sb.AppendLine("        }");
        }
        sb.AppendLine("    }");
        sb.AppendLine();

        if (complex.Length != 0)
        {
            sb.AppendLine("    private void ReleaseCapturedChildren(__SizedSnapshot snapshot)");
            sb.AppendLine("    {");
            foreach (var parameter in complex)
            {
                if (useHotChildCores &&
                    TryGetStaticGeneratedCodecCoreType(parameter.Type, concreteCodecTypes, out _))
                {
                    sb.AppendLine($"        if (snapshot.__nestedSnapshot_{parameter.Name} is not null)");
                    sb.AppendLine($"            __codec_{parameter.Name}.ReleaseSnapshot(snapshot.__nestedSnapshot_{parameter.Name});");
                }
                else
                {
                    sb.AppendLine($"        var __sized_{parameter.Name} = __sizedCodec_{parameter.Name};");
                    sb.AppendLine($"        if (__sized_{parameter.Name} is not null && snapshot.__nestedSnapshot_{parameter.Name} is not null)");
                    sb.AppendLine($"            __sized_{parameter.Name}.ReleaseSnapshot(snapshot.__nestedSnapshot_{parameter.Name});");
                }
            }
            sb.AppendLine("    }");
            sb.AppendLine();
        }

        sb.AppendLine($"    public void SerializeSized(in {requestType} value, IBufferWriter<byte> buffer, int size, IRpcSizedCodecSnapshot? snapshot)");
        sb.AppendLine("    {");
        sb.AppendLine("        ArgumentNullException.ThrowIfNull(buffer);");
        if (complex.Length != 0)
        {
            sb.AppendLine("        if (snapshot is not __SizedSnapshot __snapshot)");
            sb.AppendLine("            throw new ArgumentException(\"Generated request sized serialization requires its captured snapshot.\", nameof(snapshot));");
        }
        if (blittable.Length != 0)
        {
            sb.AppendLine($"        var fixedSpan = buffer.GetSpan({fixedSize});");
            sb.AppendLine("        var fixedOffset = 0;");
            foreach (var parameter in blittable)
            {
                var value = complex.Length == 0
                    ? $"value.{EscapeIdentifier(parameter.Name)}"
                    : $"__snapshot.__value_{parameter.Name}";
                var parameterSize = GetInlineSizeToken(parameter.Type);
                if (IsBooleanType(parameter.Type))
                    sb.AppendLine($"        fixedSpan[fixedOffset] = {value} ? (byte)1 : (byte)0;");
                else
                    sb.AppendLine($"        Unsafe.WriteUnaligned(ref System.Runtime.InteropServices.MemoryMarshal.GetReference(fixedSpan.Slice(fixedOffset, {parameterSize})), {value});");
                sb.AppendLine($"        fixedOffset += {parameterSize};");
            }
            sb.AppendLine($"        buffer.Advance({fixedSize});");
        }
        foreach (var parameter in complex)
        {
            sb.AppendLine("        var lengthSpan = buffer.GetSpan(sizeof(int));");
            sb.AppendLine($"        BinaryPrimitives.WriteInt32LittleEndian(lengthSpan, __snapshot.__nestedSize_{parameter.Name});");
            sb.AppendLine("        buffer.Advance(sizeof(int));");
            if (useHotChildCores &&
                TryGetStaticGeneratedCodecCoreType(parameter.Type, concreteCodecTypes, out _))
            {
                sb.AppendLine($"        __codec_{parameter.Name}.SerializeSized(__snapshot.__value_{parameter.Name}!, buffer, __snapshot.__nestedSize_{parameter.Name}, __snapshot.__nestedSnapshot_{parameter.Name});");
            }
            else
            {
                sb.AppendLine($"        (__sizedCodec_{parameter.Name} ?? throw new InvalidOperationException(\"Generated request exact-size capability changed after binding.\")).SerializeSized(__snapshot.__value_{parameter.Name}!, buffer, __snapshot.__nestedSize_{parameter.Name}, __snapshot.__nestedSnapshot_{parameter.Name});");
            }
        }
        sb.AppendLine("    }");
        sb.AppendLine();

        sb.AppendLine("    public void ReleaseSnapshot(IRpcSizedCodecSnapshot? snapshot)");
        sb.AppendLine("    {");
        if (complex.Length == 0)
        {
            sb.AppendLine("    }");
        }
        else
        {
            sb.AppendLine("        if (snapshot is not __SizedSnapshot __snapshot)");
            sb.AppendLine("            return;");
            sb.AppendLine("        try");
            sb.AppendLine("        {");
            sb.AppendLine("            ReleaseCapturedChildren(__snapshot);");
            sb.AppendLine("        }");
            sb.AppendLine("        finally");
            sb.AppendLine("        {");
            sb.AppendLine("            ReturnSnapshot(__snapshot);");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
        }
    }

    private static void AppendGeneratedStreams(
        StringBuilder sb,
        RpcInterfaceModel model,
        RpcMethodModel method,
        IReadOnlyDictionary<string, string> concreteCodecTypes)
    {
        var streamsType = GetStreamsType(model, method);
        var streams = GetStreamParameters(method);
        sb.AppendLine($"internal readonly struct {streamsType} : IRpcClientStreamWriter");
        sb.AppendLine("{");
        foreach (var stream in streams)
        {
            sb.AppendLine($"    private readonly {stream.DisplayType} _{stream.Name};");
            sb.AppendLine($"    private readonly {GetCodecHotStorageType(stream.DisplayStreamItemType!, stream.StreamItemType!, concreteCodecTypes)} __codec_{stream.Name};");
        }
        sb.AppendLine($"    internal {streamsType}({string.Join(", ", streams.Select(stream => $"{stream.DisplayType} {EscapeIdentifier(stream.Name)}, {GetCodecHotStorageType(stream.DisplayStreamItemType!, stream.StreamItemType!, concreteCodecTypes)} __codec_{stream.Name}"))})");
        sb.AppendLine("    {");
        foreach (var stream in streams)
        {
            sb.AppendLine($"        _{stream.Name} = {EscapeIdentifier(stream.Name)};");
            sb.AppendLine($"        this.__codec_{stream.Name} = __codec_{stream.Name};");
        }
        sb.AppendLine("    }");

        if (streams.Length == 1)
        {
            var stream = streams[0];
            var sendMethod = TryGetStaticGeneratedCodecCoreType(stream.StreamItemType!, concreteCodecTypes, out _)
                ? "SendGeneratedClientStreamAsync"
                : "SendClientStreamAsync";
            sb.AppendLine("    public ValueTask WriteAsync(IRpcClientStreamSink sink, long requestId, CancellationToken cancellationToken)");
            sb.AppendLine($"        => new(sink.{sendMethod}(requestId, (ushort)1, _{stream.Name}, __codec_{stream.Name}, cancellationToken));");
        }
        else
        {
            sb.AppendLine("    public async ValueTask WriteAsync(IRpcClientStreamSink sink, long requestId, CancellationToken cancellationToken)");
            sb.AppendLine("    {");
            for (var index = 0; index < streams.Length; index++)
            {
                var stream = streams[index];
                var sendMethod = TryGetStaticGeneratedCodecCoreType(stream.StreamItemType!, concreteCodecTypes, out _)
                    ? "SendGeneratedClientStreamAsync"
                    : "SendClientStreamAsync";
                sb.AppendLine($"        var pending_{index} = sink.{sendMethod}(requestId, (ushort){index + 1}, _{stream.Name}, __codec_{stream.Name}, cancellationToken);");
            }
            sb.AppendLine($"        await Task.WhenAll({string.Join(", ", Enumerable.Range(0, streams.Length).Select(static index => $"pending_{index}"))}).ConfigureAwait(false);");
            sb.AppendLine("    }");
        }
        sb.AppendLine("}");
    }

    private static RpcParameterModel[] GetPayloadParameters(RpcMethodModel method)
        => method.Parameters
            .Where(static parameter => !parameter.IsStream && !parameter.IsCancellationToken)
            .ToArray();

    private static RpcParameterModel[] GetStreamParameters(RpcMethodModel method)
        => method.Parameters.Where(static parameter => parameter.IsStream).ToArray();

    private static string GetResponseType(RpcMethodModel method)
        => method.IsStreamReturn ? method.DisplayStreamItemType! : method.IsVoid ? "byte" : method.DisplayGenericArgumentType!;

    private static string GetResponseCodecLookupType(RpcMethodModel method)
        => method.IsStreamReturn ? method.StreamItemType! : method.IsVoid ? "byte" : method.GenericArgumentType!;

    private static string GetMethodKind(RpcMethodModel method)
    {
        var hasStreams = GetStreamParameters(method).Length != 0;
        if (method.IsStreamReturn)
            return hasStreams ? "DuplexStreaming" : "ServerStreaming";
        if (method.IsOneWay)
            return "OneWay";
        return hasStreams ? "ClientStreaming" : "Unary";
    }

    private static string GetMethodSuffix(RpcMethodModel method)
        => unchecked((ulong)method.Hash).ToString("X16", InvariantCulture);

    private static string GetRequestType(RpcInterfaceModel model, RpcMethodModel method)
        => $"__{model.Name}_SharpLinkRequest_{GetMethodSuffix(method)}";

    private static string GetRequestCodecType(RpcInterfaceModel model, RpcMethodModel method)
        => $"__{model.Name}_SharpLinkRequestCodec_{GetMethodSuffix(method)}";

    private static string GetStreamsType(RpcInterfaceModel model, RpcMethodModel method)
        => $"__{model.Name}_SharpLinkStreams_{GetMethodSuffix(method)}";

    private static string GetInlineSizeToken(string typeName)
        => TryGetConstantSize(typeName, out var size)
            ? size.ToString(InvariantCulture)
            : GetSizeExpression(typeName);
