namespace SharpLink.Generator;

public partial class RpcGenerator
{
    private const string GeneratedAssemblyManifestAttributeMetadataName =
        "SharpLink.Abstractions.SharpLinkGeneratedAssemblyManifestAttribute";

    private static EquatableArray<ReferencedManifestBootstrapModel> AnalyzeReferencedManifestBootstraps(
        Compilation compilation,
        CancellationToken cancellationToken)
    {
        // Key by assembly + manifest identity so multiple alias references do not
        // emit duplicate registrations. Prefer global reachability when present,
        // otherwise the lexicographically first valid alias.
        var manifests = new Dictionary<(string Assembly, string Manifest), ReferencedManifestBootstrapModel>();
        foreach (var reference in compilation.References)
        {
            cancellationToken.ThrowIfCancellationRequested();
            if (compilation.GetAssemblyOrModuleSymbol(reference) is not IAssemblySymbol assembly)
                continue;

            foreach (var attribute in assembly.GetAttributes())
            {
                if (attribute.AttributeClass?.ToDisplayString() != GeneratedAssemblyManifestAttributeMetadataName ||
                    attribute.ConstructorArguments.Length != 5 ||
                    attribute.ConstructorArguments[0].Value is not INamedTypeSymbol manifestType ||
                    attribute.ConstructorArguments[1].Value is not 5 ||
                    attribute.ConstructorArguments[2].Value is not 2 ||
                    attribute.ConstructorArguments[3].Value is not string generatorVersion ||
                    string.IsNullOrWhiteSpace(generatorVersion) ||
                    attribute.ConstructorArguments[4].Value is not string abiIdentity ||
                    !string.Equals(abiIdentity, GeneratedAbiIdentity, StringComparison.Ordinal) ||
                    !SymbolEqualityComparer.Default.Equals(manifestType.ContainingAssembly, assembly))
                {
                    continue;
                }

                var hasRegisterMethod = manifestType.GetMembers("Register")
                    .OfType<IMethodSymbol>()
                    .Any(static method =>
                        method.IsStatic &&
                        method.DeclaredAccessibility == Accessibility.Public &&
                        method.MethodKind == MethodKind.Ordinary &&
                        method.Arity == 0 &&
                        method.Parameters.Length == 0 &&
                        method.ReturnsVoid);
                var hasInstance = manifestType.GetMembers("Instance")
                    .Any(static member =>
                        member is IFieldSymbol &&
                        member.IsStatic &&
                        member.DeclaredAccessibility == Accessibility.Public);
                if (!hasRegisterMethod && !hasInstance)
                    continue;

                var identity = assembly.Identity.ToString();
                var manifestName = manifestType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                var aliases = reference.Properties.Aliases;
                var selectedAlias = aliases.IsDefaultOrEmpty ||
                                    aliases.Any(static alias => alias == "global")
                    ? null
                    : aliases.OrderBy(static alias => alias, StringComparer.Ordinal).First();
                var key = (identity, manifestName);
                var candidate = new ReferencedManifestBootstrapModel(
                    identity, manifestName, hasRegisterMethod, selectedAlias);
                if (!manifests.TryGetValue(key, out var current) ||
                    (current.ExternAlias is not null &&
                     (selectedAlias is null ||
                      string.CompareOrdinal(selectedAlias, current.ExternAlias) < 0)))
                {
                    manifests[key] = candidate;
                }
            }
        }

        return manifests.Values
            .OrderBy(static manifest => manifest.AssemblyIdentity, StringComparer.Ordinal)
            .ThenBy(static manifest => manifest.ManifestTypeName, StringComparer.Ordinal)
            .ToImmutableArray();
    }

    private static string GenerateReferencedManifestBootstrap(
        EquatableArray<ReferencedManifestBootstrapModel> manifests)
    {
        if (manifests.Length == 0)
            return string.Empty;

        var sb = new StringBuilder();
        var writer = new CodeWriter(sb);
        writer.WriteLine("// <auto-generated/>");
        writer.WriteLine("#nullable enable");
        foreach (var alias in manifests
                     .Select(static manifest => manifest.ExternAlias)
                     .Where(static alias => alias is not null)
                     .Distinct(StringComparer.Ordinal)
                     .OrderBy(static alias => alias, StringComparer.Ordinal))
        {
            writer.WriteLine($"extern alias {EscapeIdentifier(alias!)};");
        }
        writer.WriteLine();
        writer.WriteLine("namespace SharpLink.Generated;");
        writer.WriteLine();
        writer.WriteLine("[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
        writer.OpenBlock("internal static class __SharpLinkGeneratedReferencedAssemblyBootstrap");
        writer.WriteLine("[global::System.Runtime.CompilerServices.ModuleInitializer]");
        writer.OpenBlock("internal static void RegisterReferencedAssemblies()");
        foreach (var manifest in manifests)
        {
            var typeReference = manifest.ExternAlias is null
                ? manifest.ManifestTypeName
                : EscapeIdentifier(manifest.ExternAlias) + "::" +
                  manifest.ManifestTypeName.Substring("global::".Length);
            if (manifest.HasRegisterMethod)
                writer.WriteLine($"{typeReference}.Register();");
            else
                writer.WriteLine($"global::SharpLink.Abstractions.SharpLinkGeneratedAssemblyCatalog.Register({typeReference}.Instance);");
        }
        writer.CloseBlock();
        writer.CloseBlock();
        return sb.ToString();
    }
}
